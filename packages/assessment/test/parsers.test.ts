import { describe, expect, it } from "vitest";
import { isValidName } from "@appport/protocol";
import { SourceSyntaxError, bodyFacts, isGeneratedGo, parseGo, signatureTypes, tokenizeGo } from "../src/go.js";
import { parseIgnore } from "../src/files.js";
import { parseProto } from "../src/proto.js";
import { messageSchema, proposeCapabilityName } from "../src/proposal.js";

describe("Go reader", () => {
  it("tokenizes literals and comments without mistaking their contents for code", () => {
    const tokens = tokenizeGo('// func Fake() {\n/* { */ x := "a\\"}" + `multi\nline {` + \'}\'\nfunc Real() {}\n');
    expect(tokens.filter((t) => t.kind === "string").map((t) => [t.value, t.line, t.endLine])).toEqual([
      ['a"}', 2, 2],
      ["multi\nline {", 2, 3]
    ]);
    expect(tokens.find((t) => t.value === "Real")!.line).toBe(4);
    expect(parseGo('package p\n// func Fake() {}\nvar s = "func Fake() {}"\nfunc Real() {}\n').functions.map((f) => f.name)).toEqual(["Real"]);
  });

  it("rejects unterminated literals and unbalanced brackets with a line", () => {
    for (const source of ['package p\nvar s = "open\n', "package p\nvar s = `open\n", "package p\n/* open\n", "package p\nfunc f() {\n"]) {
      expect(() => parseGo(source)).toThrow(SourceSyntaxError);
    }
    try {
      parseGo('package p\n\nvar s = "open\n');
    } catch (error) {
      expect((error as SourceSyntaxError).line).toBe(3);
    }
  });

  it("parses receivers, generics, results, structs with embedded fields, and interface signatures", () => {
    const file = parseGo(`package store

import (
	"context"
	pb "example.com/gen/api"
	_ "embed"
)

type Store struct {
	pb.UnimplementedServer
	*Base
	driver Driver
	a, b   int \`json:"a"\`
	cb     func(x int) (string, error)
}

type Driver interface {
	Get(ctx context.Context, id int32) (*Item, error)
	List(context.Context) ([]*Item, error)
}

func (s *Store) Get(ctx context.Context, id int32) (*Item, error) {
	return s.driver.Get(ctx, id)
}

func (c *Cache[K, V]) Put(key K, value V) {}

func Map[T any](xs []T, f func(T) T) []T { return nil }
`);
    expect(file.imports.map((i) => [i.name, i.path])).toEqual([["context", "context"], ["pb", "example.com/gen/api"], ["_", "embed"]]);
    expect(file.types[0]!.fields.map((f) => [f.name, f.type, f.embedded])).toEqual([
      ["UnimplementedServer", "pb.UnimplementedServer", true],
      ["Base", "*Base", true],
      ["driver", "Driver", false],
      ["a", "int", false],
      ["b", "int", false],
      ["cb", "func(x int) (string, error)", false]
    ]);
    expect(file.types[1]!.signatures).toEqual([
      { name: "Get", params: "ctx context.Context, id int32", results: "*Item, error" },
      { name: "List", params: "context.Context", results: "[]*Item, error" }
    ]);
    expect(file.functions.map((f) => [f.receiverType, f.receiverName, f.name, f.startLine, f.endLine])).toEqual([
      ["Store", "s", "Get", 22, 24],
      ["Cache", "c", "Put", 26, 26],
      [undefined, undefined, "Map", 28, 28]
    ]);
    const facts = bodyFacts(file.tokens, file.functions[0]!.body!);
    expect(facts.calls).toEqual([{ chain: ["s", "driver", "Get"], line: 23 }]);
  });

  it("extracts calls, selectors, strings and goroutines from a body", () => {
    const file = parseGo('package p\nfunc f() {\n\tif x := len(a); x > 0 {\n\t\treturn status.Error(codes.NotFound, "SELECT 1")\n\t}\n\tgo run()\n\tdefer s.mu.Unlock()\n}\n');
    const facts = bodyFacts(file.tokens, file.functions[0]!.body!);
    expect(facts.calls.map((c) => c.chain.join("."))).toEqual(["status.Error", "run", "s.mu.Unlock"]);
    expect(facts.selectors.map((c) => c.chain.join("."))).toEqual(["codes.NotFound"]);
    expect(facts.strings).toEqual([{ value: "SELECT 1", line: 4, endLine: 4 }]);
    expect(facts.goStatements).toEqual([6]);
  });

  it("recognizes the generated-code marker only before the package clause", () => {
    expect(isGeneratedGo("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage p\n")).toBe(true);
    expect(isGeneratedGo("package p\n\n// Code generated by hand. DO NOT EDIT.\n")).toBe(false);
    expect(isGeneratedGo("// Code generated by x. Edit freely.\npackage p\n")).toBe(false);
  });

  it("normalizes signatures to their types", () => {
    expect(signatureTypes("ctx context.Context, a, b int")).toEqual(["context.Context", "int", "int"]);
    expect(signatureTypes("context.Context, *FindUser")).toEqual(["context.Context", "*FindUser"]);
    expect(signatureTypes("m map[string]int, f func(a, b int) error")).toEqual(["map[string]int", "func(a, b int) error"]);
    expect(signatureTypes("")).toEqual([]);
  });
});

describe("Protocol Buffers reader", () => {
  const file = parseProto(`syntax = "proto3";
package acme.v1;
import "google/api/annotations.proto";
option go_package = "gen/acme";

service Things {
  option (google.api.default_host) = "acme";
  rpc GetThing(GetThingRequest) returns (Thing) {
    option (google.api.http) = {
      get: "/v1/{name=things/*}"
      additional_bindings { get: "/v1/legacy/{name=things/*}" }
    };
  }
  rpc Watch(stream WatchRequest) returns (stream .acme.v1.Thing);
}

message Thing {
  string name = 1 [(google.api.field_behavior) = IDENTIFIER, (google.api.field_behavior) = OUTPUT_ONLY];
  repeated string tags = 2;
  map<string, int64> counts = 3;
  oneof owner { string user = 4; string team_id = 5 [json_name = "team"]; }
  message Part { int32 size = 1; }
  Part part = 6;
  enum Kind { KIND_UNSPECIFIED = 0; BIG = 1 [deprecated = true]; }
  Kind kind = 7;
  reserved 8, 9;
}
message GetThingRequest { string name = 1 [(google.api.field_behavior) = REQUIRED]; }
message WatchRequest {}
`);

  it("reads services, methods, HTTP bindings and streaming", () => {
    const [service] = file.services;
    expect(service!.fullName).toBe("acme.v1.Things");
    expect(service!.methods.map((m) => [m.name, m.input, m.output, m.clientStreaming, m.serverStreaming, m.http?.method, m.http?.path, m.additionalBindings, m.startLine])).toEqual([
      ["GetThing", "GetThingRequest", "Thing", false, false, "get", "/v1/{name=things/*}", 1, 8],
      ["Watch", "WatchRequest", ".acme.v1.Thing", true, true, undefined, undefined, 0, 14]
    ]);
  });

  it("reads fields, labels, maps, oneofs, json names, behaviors and nested types", () => {
    const thing = file.messages.find((m) => m.fullName === "acme.v1.Thing")!;
    expect(thing.fields.map((f) => [f.name, f.jsonName, f.type, f.label, f.oneof, f.behaviors])).toEqual([
      ["name", "name", "string", "singular", undefined, ["IDENTIFIER", "OUTPUT_ONLY"]],
      ["tags", "tags", "string", "repeated", undefined, []],
      ["counts", "counts", "map<string, int64>", "singular", undefined, []],
      ["user", "user", "string", "singular", "owner", []],
      ["team_id", "team", "string", "singular", "owner", []],
      ["part", "part", "Part", "singular", undefined, []],
      ["kind", "kind", "Kind", "singular", undefined, []]
    ]);
    expect(file.messages.map((m) => m.fullName)).toContain("acme.v1.Thing.Part");
    expect(file.enums.map((e) => [e.fullName, e.values])).toEqual([["acme.v1.Thing.Kind", ["KIND_UNSPECIFIED", "BIG"]]]);
  });

  it("derives proto3 JSON schemas, with nested messages under $defs", () => {
    const index = { messages: new Map(file.messages.map((m) => [m.fullName, m])), enums: new Map(file.enums.map((e) => [e.fullName, e])) };
    const input = messageSchema(index, "acme.v1.Thing", "input");
    expect(input.unresolved).toEqual([]);
    expect(Object.keys(input.schema.properties!)).not.toContain("name"); // OUTPUT_ONLY
    expect(input.schema.properties!.counts).toEqual({ type: "object", additionalProperties: { type: "string", pattern: "^-?[0-9]+$" } });
    expect(input.schema.properties!.kind).toEqual({ type: "string", enum: ["KIND_UNSPECIFIED", "BIG"] });
    expect(input.schema.properties!.part).toEqual({ $ref: "#/$defs/acme.v1.Thing.Part" });
    expect(messageSchema(index, "acme.v1.GetThingRequest", "input").schema.required).toEqual(["name"]);
    expect(Object.keys(messageSchema(index, "acme.v1.Thing", "output").schema.properties!)).toContain("name");
  });

  it("rejects malformed definitions with a line", () => {
    expect(() => parseProto("service S {\n  rpc X(\n")).toThrow(SourceSyntaxError);
    expect(() => parseProto('message M { string a = 1 }\n')).toThrow(SourceSyntaxError);
    expect(() => parseProto("bogus;\n")).toThrow(SourceSyntaxError);
  });
});

describe("proposals and ignore rules", () => {
  it("proposes only valid AppPort names", () => {
    expect(proposeCapabilityName("GetMemo")).toBe("memo.get");
    expect(proposeCapabilityName("ListMemoComments")).toBe("memo.comments.list");
    expect(proposeCapabilityName("BatchGetLinkMetadata")).toBe("link.metadata.batchget");
    expect(proposeCapabilityName("GetHTTPConfig")).toBeUndefined(); // "http" is a reserved transport segment
    expect(proposeCapabilityName("Ping")).toBeUndefined();
    for (const name of ["memo.get", "memo.comments.list"]) expect(isValidName(name)).toBe(true);
  });

  it("interprets a .gitignore subset and returns what it cannot interpret", () => {
    const { matchers, unsupported } = parseIgnore("# c\n\nbuild/\n*.log\n/root.txt\ndocs/*.md\n!keep.log\n**/x\n[ab].txt\n");
    const ignored = (p: string, d = false) => matchers.some((m) => m(p, d));
    expect(ignored("build", true)).toBe(true);
    expect(ignored("build", false)).toBe(false);
    expect(ignored("a/b/c.log")).toBe(true);
    expect(ignored("root.txt")).toBe(true);
    expect(ignored("sub/root.txt")).toBe(false);
    expect(ignored("docs/a.md")).toBe(true);
    expect(ignored("docs/sub/a.md")).toBe(false);
    expect(unsupported).toEqual(["!keep.log", "**/x", "[ab].txt"]);
  });
});
