/**
 * Safety and integrity: hostile or degenerate repositories, tampered artifacts, and the guarantees an assessment never
 * gives up (no execution, no writes, no authority, no verified claims).
 */
import { chmodSync, mkdirSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { readRepositoryFile, walkRepository } from "../src/files.js";
import { RepositoryError, assessRepository, verifyAssessment, type ApplicationAssessment } from "../src/index.js";
import { clone, reseal, syntheticApp, tempDir, treeHash, writeTree } from "./helpers.js";

const codes = (a: unknown, options?: { repository?: string }) => verifyAssessment(a, options).findings.map((f) => f.code);
const app = (extra: Record<string, string> = {}, order: "as-given" | "reversed" = "as-given") => writeTree(tempDir(), syntheticApp(extra), order);

describe("repository input", () => {
  it("refuses a path that does not exist or is not a directory", () => {
    expect(() => assessRepository(join(tempDir(), "missing"))).toThrow(RepositoryError);
    const file = join(tempDir(), "file.go");
    writeFileSync(file, "package x\n");
    expect(() => assessRepository(file)).toThrow(RepositoryError);
  });

  it("assesses an empty repository as complete, with no candidates and no recommendation", () => {
    const a = assessRepository(tempDir());
    expect(a.candidates).toEqual([]);
    expect(a.recommendation).toBeNull();
    expect(a.coverage).toMatchObject({ filesSeen: 0, filesAnalyzed: 0, partial: false });
    expect(a.findings.map((f) => f.code)).toEqual(["NO_ENTRY_POINTS", "REVISION_UNKNOWN"]);
    expect(verifyAssessment(a).ok).toBe(true);
  });

  it("counts unsupported languages and marks the assessment partial", () => {
    const a = assessRepository(writeTree(tempDir(), { "app.py": "def handler():\n    return 1\n", "lib/util.rb": "puts 1\n" }));
    expect(a.coverage.languages).toEqual([
      { language: "python", files: 1, supported: false },
      { language: "ruby", files: 1, supported: false }
    ]);
    expect(a.coverage).toMatchObject({ filesAnalyzed: 0, partial: true, partialReasons: ["unsupported-languages"] });
    expect(a.findings.filter((f) => f.code === "LANGUAGE_UNSUPPORTED")).toHaveLength(2);
  });

  it("reports malformed files and keeps assessing the rest", () => {
    const root = app({ "server/broken.go": 'package server\n\nfunc broken() {\n\ts := "unterminated\n}\n', "proto/broken.proto": "service Broken {\n  rpc X(\n", "web/package.json": "{ not json" });
    const a = assessRepository(root);
    expect(a.coverage.malformed.map((m) => [m.path, m.line])).toEqual([
      ["proto/broken.proto", 2],
      ["server/broken.go", 4],
      ["web/package.json", 1]
    ]);
    expect(a.coverage.partialReasons).toContain("malformed-files");
    expect(a.findings.filter((f) => f.code === "FILE_MALFORMED").map((f) => f.path)).toEqual(["proto/broken.proto", "server/broken.go", "web/package.json"]);
    expect(a.candidates.map((c) => c.id)).toEqual(["cand-notes.v1.NoteService.DeleteNote", "cand-notes.v1.NoteService.GetNote"]);
  });

  it.skipIf(process.getuid?.() === 0)("reports unreadable files and directories", () => {
    const root = app({ "server/secret.go": "package server\n", "locked/a.go": "package locked\n" });
    chmodSync(join(root, "server/secret.go"), 0o000);
    chmodSync(join(root, "locked"), 0o000);
    try {
      const a = assessRepository(root);
      expect(a.coverage.skipped).toEqual(expect.arrayContaining([{ path: "locked", reason: "unreadable" }, { path: "server/secret.go", reason: "unreadable" }]));
      expect(a.coverage.partialReasons).toContain("unreadable-files");
    } finally {
      chmodSync(join(root, "server/secret.go"), 0o644);
      chmodSync(join(root, "locked"), 0o755);
    }
  });

  it("skips ignored, excluded, generated, binary and oversized files, each with a reason", () => {
    const root = app({
      ".gitignore": "# comment\nsecrets/\n*.local.go\n/rootonly.go\n!keep.go\n**/deep\n",
      "secrets/keys.go": "package secrets\n",
      "server/dev.local.go": "package server\n",
      "rootonly.go": "package main\n",
      "node_modules/dep/index.go": "package dep\n",
      "vendor/github.com/x/y.go": "package y\n",
      "gen/notes/notes.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage notes\n",
      "assets/logo.png": "\u0000PNG",
      "big.go": `package main\n\n// ${"x".repeat(2048)}\n`
    });
    const a = assessRepository(root, { maxFileBytes: 2000 });
    expect(a.coverage.skipped).toEqual([
      { path: "assets/logo.png", reason: "binary" },
      { path: "big.go", reason: "too-large" },
      { path: "gen/notes/notes.pb.go", reason: "generated" },
      { path: "node_modules", reason: "excluded-directory" },
      { path: "rootonly.go", reason: "ignored" },
      { path: "secrets", reason: "ignored" },
      { path: "server/dev.local.go", reason: "ignored" },
      { path: "vendor", reason: "excluded-directory" }
    ]);
    expect(a.coverage.unsupportedIgnorePatterns).toEqual(["!keep.go", "**/deep"]);
    expect(a.evidence.some((e) => /^(secrets|node_modules|vendor|gen)\//.test(e.location?.path ?? ""))).toBe(false);
  });

  it("never follows symbolic links, inside or outside the root", () => {
    const outside = writeTree(tempDir(), { "evil.go": 'package evil\n\nfunc (s *Service) GetNote() { _ = "SELECT * FROM secrets " }\n', "dir/x.proto": "service Evil {}\n" });
    const root = app();
    symlinkSync(join(outside, "evil.go"), join(root, "server/evil.go"));
    symlinkSync(join(outside, "dir"), join(root, "linked"));
    symlinkSync(join(root, "store/store.go"), join(root, "server/alias.go"));
    const a = assessRepository(root);
    expect(a.coverage.skipped.filter((s) => s.reason === "symlink").map((s) => s.path)).toEqual(["linked", "server/alias.go", "server/evil.go"]);
    expect(a.findings.filter((f) => f.code === "SYMLINK_SKIPPED")).toHaveLength(3);
    expect(JSON.stringify(a)).not.toContain(outside);
    expect(a.candidates.map((c) => (c.operation.kind === "rpc" ? c.operation.service : ""))).not.toContain("Evil");
    expect(() => readRepositoryFile(root, "server/evil.go")).toThrow(RepositoryError);
  });

  it("contains every read inside the root", () => {
    const root = app();
    expect(() => readRepositoryFile(root, "../outside.go")).toThrow(/escapes the repository root/);
    expect(() => readRepositoryFile(root, "/etc/hostname")).toThrow(/escapes the repository root/);
    for (const e of assessRepository(root).evidence) if (e.location) expect(e.location.path.startsWith("/") || e.location.path.split("/").includes("..")).toBe(false);
  });

  it("does not modify the target, and reads git identity without running git", () => {
    const root = app();
    mkdirSync(join(root, ".git/refs/heads"), { recursive: true });
    writeFileSync(join(root, ".git/HEAD"), "ref: refs/heads/trunk\n");
    writeFileSync(join(root, ".git/refs/heads/trunk"), `${"a".repeat(40)}\n`);
    writeFileSync(join(root, ".git/config"), '[remote "origin"]\n\turl = https://user:token@example.com/notes.git\n');
    const before = treeHash(root);
    const a = assessRepository(root);
    expect(treeHash(root)).toBe(before);
    expect(a.target).toEqual({ name: "notes", nameSource: "go.mod", repository: "https://example.com/notes.git", revision: "a".repeat(40), ref: "refs/heads/trunk" });
    expect(JSON.stringify(a)).not.toContain("token");
  });
});

describe("analysis of the synthetic service", () => {
  const a = assessRepository(app());
  const get = a.candidates.find((c) => c.operation.method === "GetNote")!;
  const del = a.candidates.find((c) => c.operation.method === "DeleteNote")!;

  it("links handlers, follows calls into the store, and classifies SQL reads and writes", () => {
    expect(get.implementation).toMatchObject({ symbol: "server:Service.GetNote", link: "name-and-request-type" });
    expect(get.dependencies.reachableFunctions.map((f) => [f.symbol, f.depth])).toEqual([
      ["server:Service.allowed", 1],
      ["store:Store.GetNote", 1],
      ["store:scan", 2]
    ]);
    expect(get.sideEffects.persistence.map((p) => p.operation)).toEqual(["read"]);
    expect(del.sideEffects.persistence.map((p) => p.operation)).toEqual(["write"]);
    const write = a.evidence.find((e) => e.id === del.sideEffects.persistence[0]!.evidence[0])!;
    expect(write.location).toEqual({ path: "store/store.go", startLine: 18, endLine: 19 }); // a raw string spanning two lines
    // `s.db.QueryRowContext` resolves through the field's type to database/sql.
    expect(get.dependencies.externalPackages.map((p) => p.importPath)).toEqual(["database/sql", "google.golang.org/grpc/status"]);
  });

  it("ranks deterministically, and recommends the read before the delete", () => {
    expect(get.readiness.class).toBe("exposure-candidate");
    expect(del.readiness.class).toBe("exposure-candidate");
    expect(del.readiness.concerns.map((c) => c.concern)).toEqual(["writes-state"]);
    expect(a.recommendation).toMatchObject({ candidate: get.id, ranking: { position: 1, of: 2, alternatives: [del.id] } });
    expect(get.exposure.capability).toMatchObject({ name: "note.get", effect: "observation" });
    expect(del.exposure.capability).toMatchObject({ name: "note.delete", effect: "consequential" });
    expect(del.exposure.effectBasis.reasons).toEqual(["sql-write-reachable", "http-delete-binding"]);
  });

  it("is independent of file creation order and of the directory it is in", () => {
    const b = assessRepository(app({}, "reversed"));
    expect(b.digest).toBe(a.digest);
  });

  it("keeps blocking concerns from becoming exposure candidates", () => {
    const notify = 'package store\n\nimport "net/http"\n\nfunc notify() {\n\tgo func() {\n\t\t_, _ = http.Post("https://hooks.example.com", "application/json", nil)\n\t}()\n}\n';
    // Unreachable from either handler: no concern is attributed.
    const unreachable = assessRepository(app({ "store/notify.go": notify }));
    expect(unreachable.candidates.flatMap((c) => c.readiness.concerns.map((x) => x.concern))).toEqual(["writes-state"]);
    // Reached from GetNote's store call.
    const reached = assessRepository(app({ "store/notify.go": notify, "store/store.go": syntheticApp()["store/store.go"]!.replace("return scan(row)", "notify()\n\treturn scan(row)") }));
    const got = reached.candidates.find((c) => c.operation.method === "GetNote")!;
    expect(got.readiness.concerns.map((c) => c.concern)).toEqual(["outbound-http", "async-work"]);
    expect(got.readiness.class).toBe("investigate");
    expect(got.exposure.effectBasis.effect).toBe("consequential");
    expect(reached.recommendation?.candidate).toBe("cand-notes.v1.NoteService.DeleteNote");
  });

  it("grants nothing and claims no verification", () => {
    expect(a.scope).toEqual({ grantsAuthority: false, verifiesBehavior: false, modifiesTarget: false });
    for (const c of a.candidates) {
      expect(c.exposure.status).toBe("proposed");
      expect(c.exposure.authoritative).toBe(false);
      expect(c.exposure.capability && "authorization" in c.exposure.capability).toBe(false);
      expect(["exposure-candidate", "investigate", "insufficient-evidence"]).toContain(c.readiness.class);
    }
    expect(JSON.stringify(a)).not.toMatch(/"(class|status|confidence|readiness|link)":"verified"/);
  });
});

describe("artifact integrity", () => {
  const a = assessRepository(app());
  const tamper = (edit: (x: ApplicationAssessment) => void, seal = true) => {
    const x = clone(a);
    edit(x);
    return seal ? reseal(x) : x;
  };

  it("verifies an untouched artifact and detects any content change through the digest", () => {
    expect(verifyAssessment(a)).toEqual({ ok: true, findings: [] });
    expect(codes(tamper((x) => (x.candidates[0]!.name = "renamed"), false))).toEqual(["DIGEST_MISMATCH"]);
    expect(codes(tamper((x) => (x.digest = "sha256:abc"), false))).toEqual(["DIGEST_FORMAT"]);
    // The volatile block is outside the digest.
    expect(codes(tamper((x) => (x.assessment = { id: "other", createdAt: "2030-01-01T00:00:00.000Z" }), false))).toEqual([]);
  });

  it("rejects dangling references, invented ids and malformed evidence", () => {
    expect(codes(tamper((x) => x.candidates[0]!.evidence.push("ev-0000000000000000")))).toContain("EVIDENCE_REFERENCE");
    expect(codes(tamper((x) => (x.evidence[0]!.id = "ev-ffffffffffffffff"), false))).toEqual(expect.arrayContaining(["EVIDENCE_ID"]));
    expect(codes(tamper((x) => x.evidence.push({ ...x.evidence[0]! })))).toContain("EVIDENCE_DUPLICATE");
    expect(codes(tamper((x) => ((x.evidence[0] as unknown as Record<string, unknown>).confidence = 0.9)))).toContain("EVIDENCE_MEMBER");
    expect(codes(tamper((x) => (x.evidence.find((e) => e.location)!.location!.path = "../../etc/passwd")))).toContain("EVIDENCE_LOCATION");
    expect(codes(tamper((x) => delete x.evidence.find((e) => e.class === "observed" && e.method !== "scanner")!.location))).toContain("EVIDENCE_LOCATION");
  });

  it("rejects invalid evidence classes and inference without an observed basis", () => {
    expect(codes(tamper((x) => ((x.evidence[0] as { class: string }).class = "verified")))).toContain("EVIDENCE_CLASS");
    const inferred = (x: ApplicationAssessment) => x.evidence.find((e) => e.class === "inferred")!;
    expect(codes(tamper((x) => delete inferred(x).basis))).toContain("EVIDENCE_BASIS");
    expect(codes(tamper((x) => (inferred(x).basis = [x.evidence.find((e) => e.class === "unknown")!.id])))).toContain("EVIDENCE_BASIS");
  });

  it("rejects claims of verification, authority or authoritative exposure", () => {
    expect(codes(tamper((x) => ((x.candidates[0]!.readiness as { class: string }).class = "verified")))).toEqual(expect.arrayContaining(["READINESS_CLASS", "VERIFIED_CLAIM"]));
    expect(codes(tamper((x) => ((x.candidates[0] as unknown as { confidence: string }).confidence = "verified")))).toContain("VERIFIED_CLAIM");
    expect(codes(tamper((x) => ((x.scope as { grantsAuthority: boolean }).grantsAuthority = true)))).toContain("SCOPE_CLAIM");
    expect(codes(tamper((x) => ((x.scope as { verifiesBehavior: boolean }).verifiesBehavior = true)))).toContain("SCOPE_CLAIM");
    expect(codes(tamper((x) => ((x.scope as Record<string, unknown>).grant = { capability: "note.get" })))).toContain("SCOPE_CLAIM");
    expect(codes(tamper((x) => ((x.candidates[0]!.exposure as { authoritative: boolean }).authoritative = true)))).toContain("EXPOSURE_CLAIM");
    expect(codes(tamper((x) => ((x as unknown as Record<string, unknown>).grants = [])))).toContain("ASSESSMENT_MEMBER");
  });

  it("rejects a recommendation of a candidate that is not an exposure candidate, or does not exist", () => {
    expect(codes(tamper((x) => (x.recommendation!.candidate = "cand-missing")))).toContain("RECOMMENDATION");
    expect(codes(tamper((x) => (x.candidates.find((c) => c.id === x.recommendation!.candidate)!.readiness.class = "investigate")))).toContain("RECOMMENDATION");
    expect(codes(tamper((x) => x.questions.push({ id: "q-x", candidate: "cand-missing", question: "?", evidence: [] })))).toContain("QUESTION_REFERENCE");
  });

  it("refuses other formats and non-objects", () => {
    expect(codes(null)).toEqual(["ASSESSMENT_MALFORMED"]);
    expect(codes([])).toEqual(["ASSESSMENT_MALFORMED"]);
    expect(codes({ ...a, format: "appport.application-assessment/3" })).toContain("ASSESSMENT_FORMAT");
  });

  it("checks observed locations against the repository, and the revision it was taken at", () => {
    const root = app();
    const b = assessRepository(root);
    expect(verifyAssessment(b, { repository: root }).ok).toBe(true);
    writeFileSync(join(root, "store/store.go"), readFileSync(join(root, "store/store.go"), "utf8").replace(/SELECT body/, "-- body"));
    expect(codes(b, { repository: root })).toContain("LOCATION_SUBJECT");
    writeFileSync(join(root, "store/store.go"), "package store\n");
    expect(codes(b, { repository: root })).toContain("LOCATION_RANGE");
    expect(codes(b, { repository: tempDir() })).toContain("LOCATION_MISSING");
    expect(codes(tamper((x) => (x.target.revision = "b".repeat(40))), { repository: root })).toContain("REVISION_MISMATCH");
  });

  it("walks deterministically", () => {
    const one = walkRepository(app());
    const two = walkRepository(app({}, "reversed"));
    expect(two).toEqual(one);
    expect(one.files.map((f) => f.path)).toEqual([...one.files.map((f) => f.path)].sort());
  });
});
